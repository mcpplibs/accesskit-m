#!/usr/bin/env python3
"""src/accesskit.cppm from <accesskit.h>: every public name exported unchanged.

    python3 tools/gen_module.py <accesskit.h> > src/accesskit.cppm
    python3 tools/gen_module.py <accesskit.h> --check src/accesskit.cppm

Every function, struct, typedef, enum and enumerator the header declares is
exported with `export using ::name;`, under the same preprocessor condition
the header declares it under (the platform adapters exist only on their
platforms). Nothing is renamed and nothing is added: the C API as it is.
"""
import re
import sys

def scan(text: str):
    names = []          # (conditions tuple, name)
    seen = set()
    stack = []          # conditions in force
    in_enum = False
    in_comment = False
    # A directive continued over lines (a trailing backslash) is one line.
    text = re.sub(r"\\\n\s*", " ", text)
    for raw in text.splitlines():
        line = raw.strip()
        # Comments: skip /** … */ blocks and // lines.
        if in_comment:
            if "*/" in line:
                in_comment = False
            continue
        if line.startswith("/*"):
            if "*/" not in line:
                in_comment = True
            continue
        if line.startswith("//") or not line:
            continue
        if line.startswith("#"):
            directive = line[1:].strip()
            if directive.startswith(("if ", "ifdef ", "ifndef ", "if(")):
                stack.append(directive)
            elif directive.startswith("elif"):
                stack[-1] = directive.replace("elif", "if", 1)
            elif directive.startswith("else"):
                stack[-1] = "!(" + stack[-1] + ")"
            elif directive.startswith("endif"):
                if stack:
                    stack.pop()
            continue
        cond = tuple(c for c in stack if c != "ifndef ACCESSKIT_H")
        def add(name):
            if name not in seen and not name.startswith("_"):
                seen.add(name)
                names.append((cond, name))
        if in_enum:
            if line.startswith("}"):
                in_enum = False
                continue
            m = re.match(r"([A-Z][A-Z0-9_]*)\s*(=|,|$)", line)
            if m:
                add(m.group(1))
            continue
        m = re.match(r"(?:typedef\s+)?enum\s+(accesskit_\w+)", line)
        if m:
            add(m.group(1))
            in_enum = not line.endswith(";")
            continue
        m = re.match(r"typedef\s+struct\s+(accesskit_\w+)\s+(accesskit_\w+)\s*;", line)
        if m:
            add(m.group(2))
            continue
        m = re.match(r"(?:typedef\s+)?struct\s+(accesskit_\w+)", line)
        if m and not line.startswith("typedef struct accesskit_tree_update *("):
            add(m.group(1))
        m = re.match(r"typedef\s+.*?\(\*\s*(accesskit_\w+)\)", line)
        if m:
            add(m.group(1))
            continue
        m = re.match(r"typedef\s+[\w\s\*]+?\b(accesskit_\w+)\s*;", line)
        if m:
            add(m.group(1))
            continue
        # A function: a name followed by '(' at the start of its declarator.
        m = re.search(r"\b(accesskit_\w+)\s*\(", line)
        if m and not line.startswith(("typedef", "return", "if", "#")) and "(*" not in line:
            add(m.group(1))
    return names

def emit(names) -> str:
    out = [
        "// mcpplibs.mwrap.accesskit — AccessKit's C bindings as a C++ module: every",
        "// public name of <accesskit.h>, unchanged, under the same platform conditions",
        "// the header declares it under. Generated by tools/gen_module.py; do not edit.",
        "module;",
        "#include <accesskit.h>",
        "",
        "export module mcpplibs.mwrap.accesskit;",
        "",
    ]
    current = ()
    def close(c):
        for _ in c:
            out.append("#endif")
    for cond, name in names:
        if cond != current:
            close(current)
            for c in cond:
                if c.startswith("!("):
                    out.append("#if !(" + c[2:-1].replace("ifdef ", "defined ").replace("ifndef ", "!defined ").replace("if ", "", 1) + ")")
                elif c.startswith("ifdef "):
                    out.append("#ifdef " + c[6:])
                elif c.startswith("ifndef "):
                    out.append("#ifndef " + c[7:])
                else:
                    out.append("#" + c)
            current = cond
        out.append(f"export using ::{name};")
    close(current)
    return "\n".join(out) + "\n"

def main():
    header = sys.argv[1]
    text = emit(scan(open(header, encoding="utf-8").read()))
    if len(sys.argv) > 3 and sys.argv[2] == "--check":
        if open(sys.argv[3], encoding="utf-8").read() != text:
            print(f"{sys.argv[3]} is not what tools/gen_module.py makes of {header}", file=sys.stderr)
            sys.exit(1)
        return
    sys.stdout.write(text)

main()
